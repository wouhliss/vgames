/// Header of the generated file.
const BINDINGS_HEADER: &str = "// @generated by tauri-specta from apps/desktop/src-tauri. Do not edit.\n\
// Owner: Agent 2. Regenerate: VGAMES_UPDATE_BINDINGS=1 cargo test -p vgames-desktop bindings\n";

