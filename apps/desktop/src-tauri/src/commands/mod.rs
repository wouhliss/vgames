//! Typed Tauri commands and events (tauri-specta). This module is the whole
//! surface the WebView can reach. `apps/desktop/src/bindings.ts` is generated
//! from it: debug builds rewrite it at startup, and the `bindings_are_current`
//! test fails when the committed file is stale (regenerate with
//! `VGAMES_UPDATE_BINDINGS=1 cargo test -p vgames-desktop bindings`).

mod app;
mod libraries;
pub mod names;

